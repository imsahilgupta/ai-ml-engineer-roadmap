for i in range(5):
    print(f"Hello, Python! {i}")

for number in range(1, 6):
    print(number)

# use a step value in the range function
for number in range(2, 11, 2):
    print(number)

# loop through a string
language = "Python"

for character in language:
    print(character)

# Loop through a list
topics = ["Variables", "Operators", "Conditions", "Loops"]

for topic in topics:
    print(topic)